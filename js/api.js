// ─── API helpers ───────────────────────────────────────────
async function omdbFetch(params) {
  const url = new URL(BASE_URL);
  url.searchParams.set('apikey', API_KEY);
  Object.entries(params).forEach(([k, v]) => url.searchParams.set(k, v));
  const res = await fetch(url.toString());
  return res.json();
}

async function searchMovies(query, page = 1) {
  return omdbFetch({ s: query, type: 'movie', page });
}

async function getMovieById(id) {
  return omdbFetch({ i: id, plot: 'full' });
}

async function getMultipleMovies(ids) {
  const results = await Promise.all(ids.map(id => getMovieById(id)));
  return results.filter(m => m.Response === 'True');
}
